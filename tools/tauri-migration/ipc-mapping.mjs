import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const docs = resolve(root, 'docs/tauri-migration');

export const BOUNDARIES = new Set([
  'rust-command',
  'rust-command+raw-ipc',
  'rust-command+channel',
  'rust-event',
  'frontend-adapter',
  'platform-adapter',
  'not-applicable',
]);
export const STATES = new Set(['proposed', 'diagnostic-partial']);

export function loadMapping() {
  return JSON.parse(readFileSync(resolve(docs, 'ipc-mapping.json'), 'utf8'));
}

export function loadInventory() {
  return JSON.parse(readFileSync(resolve(docs, 'ipc-inventory.json'), 'utf8'));
}

export function methodsByKey(inventory) {
  const map = new Map();
  for (const entry of inventory.entries) {
    const key = entry.process + ':' + entry.kind + ':' + entry.namespace;
    if (!map.has(key)) map.set(key, []);
    map.get(key).push(entry.method);
  }
  for (const record of inventory.namespaces) {
    const key = record.process + ':' + record.kind + ':' + record.namespace;
    if (!map.has(key)) map.set(key, []);
  }
  return map;
}

const cell = text => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');

// Aligned like the repository formatter so the committed document is formatter-stable.
function table(header, align, rows) {
  const all = [header, ...rows].map(row => row.map(cell));
  const widths = header.map((_, i) =>
    Math.max(3, ...all.map(row => row[i].length))
  );
  const pad = (text, i) =>
    align[i] === 'right' ? text.padStart(widths[i]) : text.padEnd(widths[i]);
  const line = row => '| ' + row.map(pad).join(' | ') + ' |';
  const rule = widths.map((w, i) =>
    align[i] === 'right' ? '-'.repeat(w - 1) + ':' : '-'.repeat(w)
  );
  return [
    line(all[0]),
    '| ' + rule.join(' | ') + ' |',
    ...all.slice(1).map(line),
  ];
}

export function render(mapping, inventory) {
  const methods = methodsByKey(inventory);
  const lines = [
    '# IPC mapping to Tauri and Rust',
    '',
    '<!-- Generated by tools/tauri-migration/ipc-mapping.mjs from ipc-mapping.json. Do not edit. -->',
    '',
    'Reference: commit ' + mapping.reference + '.',
    '',
    mapping.statement,
    '',
    'Every namespace record of the [IPC inventory](ipc-inventory.json) has exactly one row below, and the test in tools/tauri-migration/ipc-mapping.test.mjs fails if a record, a method or a parity item is left without a destination. Rows with groups list the methods of each group so that no method is implied by its namespace.',
    '',
    '## Caller classes',
    '',
    ...Object.entries(mapping.callerClasses).map(
      ([name, text]) => '- ' + name + ': ' + text
    ),
    '',
    '## Records',
    '',
    ...table(
      [
        'Record',
        'Members',
        'Boundary',
        'Service',
        'Callers',
        'Parity',
        'State',
        'Platforms',
      ],
      ['left', 'right', 'left', 'left', 'left', 'left', 'left', 'left'],
      mapping.records.map(r => [
        r.key,
        r.members,
        r.boundary,
        r.service,
        r.callers.join(', ') || '-',
        r.matrix.join(', '),
        r.state,
        Object.entries(r.platforms)
          .map(([os, value]) => os + ': ' + value)
          .join('; '),
      ])
    ),
    '',
    '## Design notes',
    '',
  ];
  for (const r of mapping.records) {
    lines.push('### ' + r.key, '');
    lines.push('- Replaces: ' + r.replaces);
    lines.push('- Design: ' + r.design);
    for (const item of r.constraints) lines.push('- Constraint: ' + item);
    if (r.blockedBy)
      for (const item of r.blockedBy) lines.push('- Blocked by: ' + item);
    if (r.openRisk) lines.push('- Open risk: ' + r.openRisk);
    if (r.groups)
      for (const [name, list] of Object.entries(r.groups))
        lines.push(
          '- Group ' + name + ' (' + list.length + '): ' + list.join(', ')
        );
    else if (methods.get(r.key).length)
      lines.push(
        '- Methods (' + r.members + '): ' + methods.get(r.key).join(', ')
      );
    lines.push('');
  }
  lines.push(
    '## Parity surfaces outside the IPC inventory',
    '',
    ...table(
      ['Parity', 'Surface', 'Route', 'Evidence so far'],
      ['left', 'left', 'left', 'left'],
      mapping.nonIpcSurfaces.map(s => [
        s.matrix,
        s.surface,
        s.route,
        s.evidence,
      ])
    ),
    ''
  );
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(
    resolve(docs, 'ipc-mapping.md'),
    render(loadMapping(), loadInventory())
  );
}
